import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp'; // Included with Next.js.

// Dedicated hero copies: other sections retain their original photographs.
const scene = await fs.readFile('src/components/HomeStory/scene-data.ts', 'utf8');
const collage = scene.split('export const HERO_COLLAGE_IMAGES = [')[1].split('] as const')[0];
const sources = [...new Set([...collage.matchAll(/'([^']+\.webp)'/g)].map(match => match[1]))];
const directory = 'public/home-hero';
await fs.mkdir(directory, { recursive: true });
const media = {};
for (const src of sources) {
  const input = path.join('public', src);
  const metadata = await sharp(input).metadata();
  const widths = [480, 960, 1440, ...(src === '/hero-home.webp' ? [1920] : [])].filter(width => width <= metadata.width);
  const variants = [];
  for (const width of widths) {
    const url = `/home-hero/${path.basename(src, '.webp')}-${width}.webp`;
    const result = await sharp(input).rotate().resize({ width, withoutEnlargement: true })
      .webp({ quality: 76, effort: 6 }).toFile(path.join('public', url));
    variants.push({ src: url, width: result.width, bytes: result.size });
  }
  media[src] = {
    src: variants[0].src,
    srcSet: variants.map(variant => `${variant.src} ${variant.width}w`).join(', '),
    originalBytes: (await fs.stat(input)).size,
    variants,
  };
}
await fs.writeFile('src/components/HomeStory/hero-media.ts',
  '// Generated by npm run optimize:hero; keep responsive assets in public/home-hero.\n' +
  `export const HERO_MEDIA = ${JSON.stringify(media, null, 2)} as const;\n` +
  'export const HERO_TILE_SIZES = "(min-width: 1440px) 25vw, (min-width: 980px) and (min-aspect-ratio: 10/11) 25vw, 50vw";\n');
const original = Object.values(media).reduce((sum, item) => sum + item.originalBytes, 0);
const small = Object.values(media).reduce((sum, item) => sum + item.variants[0].bytes, 0);
console.log(`Hero: ${sources.length} photographs; originals ${original} bytes, 480px set ${small} bytes (${Math.round((1-small/original)*100)}% smaller).`);
